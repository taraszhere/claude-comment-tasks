package com.claudecommenttasks.run

import com.claudecommenttasks.settings.ClaudeSettingsConfigurable
import com.claudecommenttasks.toolwindow.ClaudeTasksConsole
import com.intellij.notification.Notification
import com.intellij.notification.NotificationAction
import com.intellij.notification.NotificationGroupManager
import com.intellij.notification.NotificationType
import com.intellij.openapi.actionSystem.AnAction
import com.intellij.openapi.options.ShowSettingsUtil
import com.intellij.openapi.project.Project
import com.intellij.openapi.util.text.StringUtil

object ClaudeNotifications {

    const val GROUP_ID = "Claude Comment Tasks"
    const val PROGRESS_GROUP_ID = "Claude Comment Tasks Progress"

    fun info(project: Project?, title: String, content: String, vararg actions: AnAction): Notification =
        notify(project, title, content, NotificationType.INFORMATION, *actions)

    fun warning(project: Project?, title: String, content: String, vararg actions: AnAction): Notification =
        notify(project, title, content, NotificationType.WARNING, *actions)

    fun error(project: Project?, title: String, content: String, vararg actions: AnAction): Notification =
        notify(project, title, content, NotificationType.ERROR, *actions)

    /** Sticky balloon shown while a run is in progress; expire it when the run ends. */
    fun showInProgress(project: Project, fileName: String): Notification {
        val notification = NotificationGroupManager.getInstance()
            .getNotificationGroup(PROGRESS_GROUP_ID)
            .createNotification(
                "Claude is working on $fileName",
                "Please do not edit this file until the run finishes. Use Cancel in the progress bar to stop it.",
                NotificationType.INFORMATION,
            )
        notification.notify(project)
        return notification
    }

    fun openToolWindowAction(project: Project): AnAction =
        NotificationAction.createSimple("Open Claude Tasks") { ClaudeTasksConsole.getInstance(project).show() }

    fun openSettingsAction(project: Project?): AnAction =
        NotificationAction.createSimpleExpiring("Open settings") {
            ShowSettingsUtil.getInstance().showSettingsDialog(project, ClaudeSettingsConfigurable::class.java)
        }

    /** Notification content is HTML; escape raw CLI text before showing it. */
    fun escape(text: String): String = StringUtil.escapeXmlEntities(text)

    private fun notify(
        project: Project?,
        title: String,
        content: String,
        type: NotificationType,
        vararg actions: AnAction,
    ): Notification {
        val notification = NotificationGroupManager.getInstance()
            .getNotificationGroup(GROUP_ID)
            .createNotification(title, content, type)
        for (action in actions) notification.addAction(action)
        notification.notify(project)
        return notification
    }
}
